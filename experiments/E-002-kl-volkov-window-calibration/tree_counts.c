/*
 * E-002 -- matched enumeration of the qx+1 reverse tree and of its i.i.d.
 * control, for calibrating the finite-window bias of the counting-exponent
 * estimator used in H-001 / E-001.
 *
 * Three of the five modes differ in EXACTLY one line of arithmetic, the
 * choice of the branch class r:
 *
 *   arith : r = u % q            (the branch class is the true residue)
 *   iid   : r = uniform{0..q-1}  (the branch class is an independent draw)
 *   cyc   : the branch class of the first child is an independent draw, and
 *           successive siblings advance by c = ((2^d-1)/q) mod q, which is
 *           what the arithmetic tree does exactly (see below)
 *
 * The third mode exists because of an exact congruence. Successive siblings
 * of a node satisfy w_{j+1} = 2^d w_j + (2^d-1)/q, and 2^d == 1 (mod q), so
 *
 *        w_{j+1} == w_j + (2^d - 1)/q   (mod q).
 *
 * When q does not divide (2^d-1)/q, that is when q is not a Wieferich prime
 * base 2, the residues of consecutive siblings run through a full cycle of
 * length q. Exactly one sibling in every q consecutive ones is sterile, at a
 * deterministic position. The i.i.d. model makes each sibling sterile by an
 * independent coin, which has the same mean and a much larger variance.
 * Mode `cyc` isolates that single difference.
 *
 * The fourth mode, `cycq`, is not one of those three: it keeps `cyc`'s tree
 * structure but replaces the value denominator, and runs through a separate
 * recursion (`dfs_root_q`), documented at its own head below.
 *
 * The fifth mode, `iidq`, is to `cycq` what `iid` is to `cyc`: the same
 * tunable value denominator, but each child draws its own residue instead of
 * advancing cyclically from the parent's. It exists because an external
 * referee observed that the calibration band was measured on a family built
 * to one pressure target and then carried to another target that had only a
 * single construction. `iidq` is that second construction. The two differ in
 * exactly one line of `dfs_root_q`.
 *
 * Everything else, the child recursion, the integer floor division, the
 * path-max truncation bookkeeping, the checkpoint binning, is byte-identical.
 * So any difference between those three runs is attributable to the arithmetic
 * of the residues and to nothing else.
 *
 * Admissibility rule (paper section 2 specialised to q):
 *   node u odd, r = u mod q.  r == 0 -> sterile.
 *   otherwise the children are w = (2^a u - 1)/q for a = A0[r], A0[r]+d,
 *   A0[r]+2d, ... where d = ord_q(2) and A0[r] is the unique a in {1..d}
 *   with 2^a r == 1 (mod q).
 *   Successive children satisfy w_{j+1} = 2^d w_j + (2^d - 1)/q exactly,
 *   so only the first child needs a wide multiply.
 *
 * Truncation: a node w would have been generated by a run with search bound
 * 10^B iff every node on the path root->w is <= 10^B, i.e. path_max(w) <= 10^B.
 * One pass at the largest bound therefore yields the counts at every buffer.
 *
 * No visited set is needed: the forward map is a function, so in the reverse
 * tree every node has at most one parent, and a cycle member can only be
 * reached from inside its own cycle. Roots exclude the three known positive
 * cycles and are checked for no recurrence within the forward-step cutoff
 * the paper states; unknown longer cycles are not ruled out.
 *
 * Build:  gcc -O3 -march=native -fopenmp -o tree_counts tree_counts.c -lm
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>
#ifdef _OPENMP
#include <omp.h>
#endif

typedef unsigned __int128 u128;

#define MAX_CP  24
#define MAX_BUF 24

static int      Q  = 5;      /* the multiplier q */
static int      Dd = 4;      /* d = ord_q(2) */
static int      A0[64];      /* A0[r] for r = 1..q-1, or 0 if r is sterile */
static int      FERT[64], n_fert;  /* the fertile residues */
static uint64_t STEP_ADD;    /* (2^d - 1)/q */
static uint64_t zero_nodes = 0;  /* how often a value reaches the cemetery */

static int      n_cp, n_buf;
static uint64_t cp[MAX_CP];      /* value checkpoints, ascending */
static uint64_t bufthr[MAX_BUF]; /* path-max buffers, ascending */
static uint64_t BOUND;           /* search bound = largest buffer */

/* ---- splitmix64, one independent stream per root ---- */
static inline uint64_t sm64(uint64_t *s) {
    uint64_t z = (*s += 0x9E3779B97F4A7C15ULL);
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL;
    return z ^ (z >> 31);
}

static void setup_q(int q) {
    Q = q;
    /* d = ord_q(2) */
    int d = 1;
    uint64_t p = 2 % q;
    while (p != 1) { p = (p * 2) % q; d++; }
    Dd = d;
    STEP_ADD = (((uint64_t)1 << d) - 1) / (uint64_t)q;
    /* r is fertile iff 2^a r == 1 (mod q) has a solution, i.e. iff r lies in
       the subgroup generated by 2. For q = 3, 5 every r != 0 is fertile;
       for q = 7 only r in {1,2,4} is, so 4 residues out of 7 are sterile. */
    n_fert = 0;
    A0[0] = 0;
    for (int r = 1; r < q; r++) {
        A0[r] = 0;
        for (int a = 1; a <= d; a++) {
            if ((((uint64_t)r << a) % (uint64_t)q) == 1) { A0[r] = a; break; }
        }
        if (A0[r]) FERT[n_fert++] = r;
    }
    if (!n_fert) { fprintf(stderr, "no fertile residue for q=%d\n", q); exit(1); }
}

/* stack entry; rr carries the imposed residue in mode `cyc`, unused elsewhere */
typedef struct { uint64_t u, pmax; uint32_t rr; } node_t;

enum { MODE_ARITH = 0, MODE_IID = 1, MODE_CYC = 2, MODE_CYCQ = 3, MODE_IIDQ = 4 };
static const char *MODENAME[5] = {"arith", "iid", "cyc", "cycq", "iidq"};
/* mode iidq only: draw a fresh residue per CHILD instead of once per parent
   with cyclic advance. See the header note on the fifth mode. */
static int QMODE_IID = 0;

/*
 * Mode `cycq`: the `cyc` tree structure with the value denominator replaced
 * by a real number qval, so the annealed pressure TARGET becomes tunable while the
 * branching combinatorics and the sibling congruence stay put. The exponent
 * solves qval^alpha = q (2^alpha - 1), so at q = 5:
 *     qval = 5.000  ->  alpha = 0.650919  (Kontorovich-Lagarias)
 *     qval = 5.054  ->  alpha = 0.678      (Volkov)
 * This is what makes the estimator's reading comparable between the two
 * hypotheses: run the same estimator on a process tuned to each annealed
 * pressure target, and see which reading the arithmetic tree matches.
 * Values are carried in log10, since they are no longer integers.
 */
static double QVAL_LOG10 = 0.0;
/* mode cycq only: children below this log10 value are dropped, mimicking the
   fact that the arithmetic recursion lives on positive integers and bottoms
   out around 1, while a pure real-valued walk descends without limit */
static double MIN_LOG10 = -1e9;
static double CP_LOG10[MAX_CP], BUF_LOG10[MAX_BUF];
static const double LOG10_2 = 0.30102999566398119521;

typedef struct { double L, pmaxL; uint32_t rr; } fnode_t;

static uint64_t dfs_root_q(uint64_t root, uint64_t seed, uint64_t *raw)
{
    size_t cap = 1u << 14;
    fnode_t *st = (fnode_t *)malloc(cap * sizeof(fnode_t));
    size_t sp = 0;
    uint64_t visited = 0, rng = seed;
    const uint64_t cstep = STEP_ADD % (uint64_t)Q;
    const double top = BUF_LOG10[n_buf - 1];

    st[sp].L = log10((double)root); st[sp].pmaxL = st[sp].L;
    st[sp].rr = (uint32_t)FERT[sm64(&rng) % (uint64_t)n_fert];
    sp++;

    while (sp) {
        fnode_t nd = st[--sp];
        visited++;
        int ci = 0; while (ci < n_cp && CP_LOG10[ci] < nd.L) ci++;
        if (ci < n_cp) {
            int bi = 0; while (bi < n_buf && BUF_LOG10[bi] < nd.pmaxL) bi++;
            if (bi < n_buf) raw[ci * MAX_BUF + bi]++;
        }
        uint64_t r = nd.rr;
        if (r == 0) continue;
        uint64_t cr = sm64(&rng) % (uint64_t)Q;
        for (int a = A0[r]; ; a += Dd) {
            double L = nd.L + a * LOG10_2 - QVAL_LOG10;
            if (L > top) break;
            if (L < MIN_LOG10) continue;
            if (sp + 1 >= cap) { cap <<= 1; st = (fnode_t *)realloc(st, cap * sizeof(fnode_t)); }
            st[sp].L = L;
            st[sp].pmaxL = (L > nd.pmaxL) ? L : nd.pmaxL;
            st[sp].rr = (uint32_t)(QMODE_IID ? (sm64(&rng) % (uint64_t)Q) : cr);
            sp++;
            cr = (cr + cstep) % (uint64_t)Q;
        }
    }
    free(st);
    for (int bi = 0; bi < n_buf; bi++) {
        uint64_t acc = 0;
        for (int ci = 0; ci < n_cp; ci++) { acc += raw[ci * MAX_BUF + bi]; raw[ci * MAX_BUF + bi] = acc; }
    }
    for (int ci = 0; ci < n_cp; ci++) {
        uint64_t acc = 0;
        for (int bi = 0; bi < n_buf; bi++) { acc += raw[ci * MAX_BUF + bi]; raw[ci * MAX_BUF + bi] = acc; }
    }
    return visited;
}

/*
 * DFS from one root. raw[ci][bi] accumulates, then a 2D prefix sum turns it
 * into  N(value <= cp[ci], path_max <= bufthr[bi]).
 * resid[] accumulates the residue histogram of all counted nodes.
 * Returns the number of nodes visited.
 */
static uint64_t dfs_root(uint64_t root, int mode, uint64_t seed,
                         uint64_t *raw, uint64_t *resid)
{
    size_t cap = 1u << 14;
    node_t *st = (node_t *)malloc(cap * sizeof(node_t));
    size_t sp = 0;
    uint64_t visited = 0;
    uint64_t rng = seed;
    const uint64_t cstep = STEP_ADD % (uint64_t)Q;   /* sibling residue step */

    /* the root is fertile by construction in mode `arith` (roots are sampled
       with root % q != 0), so the controls must draw a fertile root residue
       too; otherwise one control root in q is a dead tree and the comparison
       measures the root sampling rule instead of the tree */
    st[sp].u = root; st[sp].pmax = root;
    st[sp].rr = (uint32_t)(mode == MODE_ARITH ? root % (uint64_t)Q
                                              : FERT[sm64(&rng) % (uint64_t)n_fert]);
    sp++;

    while (sp) {
        node_t nd = st[--sp];
        uint64_t u = nd.u, pmax = nd.pmax;
        visited++;

        /* bin the node */
        int ci = 0; while (ci < n_cp && cp[ci] < u) ci++;   /* first cp >= u */
        if (ci < n_cp) {
            int bi = 0; while (bi < n_buf && bufthr[bi] < pmax) bi++;
            if (bi < n_buf) {
                raw[ci * MAX_BUF + bi]++;
                resid[u % (uint64_t)Q]++;
            }
        }

        /* branch class: the ONLY thing that differs between the modes */
        uint64_t r = (mode == MODE_ARITH) ? (u % (uint64_t)Q) : (uint64_t)nd.rr;
        if (r == 0) continue;                    /* sterile */

        /* Zero is a cemetery state, and it must be one EXPLICITLY.
           A contracting string of small exponents can drive a synthetic
           node's value to 0: from u=1e5, thirteen steps of a=1 reach it.
           Without this guard, u==0 gives t==0 and `t - 1` underflows in
           unsigned u128 arithmetic to 2^128-1, whose quotient by Q casts
           to 3689348814741910323. That happens to exceed every BOUND this
           experiment uses, so the node became a leaf anyway. It was an
           accident of BOUND < 3.69e18, not a decision, and it is exactly
           the convention the perturbation lemma of H-011 requires. Made
           explicit.

           CORRECAO, rodada 13 (R13-01). Este comentario afirmava que "os
           dados comitados nao sao afetados (verificado re-rodando e
           diffando)". Isso era FALSO, e a verificacao nunca foi feita: o
           `continue` pula o sorteio do RNG do MODE_CYC oito linhas
           abaixo, deslocando o fluxo de residuos. Provado por teste
           negativo executado: uma compilacao com esta linha removida, e
           so ela, reproduzia o antigo data/q5_cyc_b15.txt exatamente.

           O dado foi REGENERADO a partir deste codigo. Duas das 300
           raizes (557 e 5621) e a linha #resid mudaram. Nenhum numero
           que o paper imprime se moveu, o que foi MEDIDO e nao suposto:
           cyc segue 0.63097 na janela e 0.65122 na decada de calibracao,
           e a banda 0.00141 e a largura 0.0037 seguem iguais. Os quatro
           logs derivados foram regravados. */
        if (u == 0) {
            /* corrida de dados: dfs_root roda dentro do `omp parallel for`
               de :375 e este contador e global. Achado na rodada 14
               (R14-10). O valor so vai para o stderr, entao a corrida nao
               contamina resultado nenhum, mas um programa publicado nao
               deve carregar uma. */
#pragma omp atomic
            zero_nodes++;
            continue;
        }

        int a = A0[r];
        u128 lim = (u128)BOUND * (u128)Q + 1;    /* need 2^a u <= lim */
        u128 t = ((u128)u << a);
        if (t > lim) continue;
        uint64_t w = (uint64_t)((t - 1) / (u128)Q);

        /* residue carried by the first child in the two synthetic modes */
        uint64_t cr = (mode == MODE_CYC) ? (sm64(&rng) % (uint64_t)Q) : 0;

        while (w <= BOUND) {
            if (w != root) {
                if (sp + 1 >= cap) {
                    cap <<= 1;
                    st = (node_t *)realloc(st, cap * sizeof(node_t));
                }
                st[sp].u = w;
                st[sp].pmax = (w > pmax) ? w : pmax;
                st[sp].rr = (uint32_t)(mode == MODE_IID ? sm64(&rng) % (uint64_t)Q : cr);
                sp++;
            }
            /* w_{j+1} = 2^d w_j + (2^d-1)/q, exact; residues advance by cstep */
            if (w > (BOUND >> Dd)) break;
            w = (w << Dd) + STEP_ADD;
            cr = (cr + cstep) % (uint64_t)Q;
        }
    }
    free(st);

    /* 2D prefix sum: cumulative in checkpoint, then in buffer */
    for (int bi = 0; bi < n_buf; bi++) {
        uint64_t acc = 0;
        for (int ci = 0; ci < n_cp; ci++) { acc += raw[ci * MAX_BUF + bi]; raw[ci * MAX_BUF + bi] = acc; }
    }
    for (int ci = 0; ci < n_cp; ci++) {
        uint64_t acc = 0;
        for (int bi = 0; bi < n_buf; bi++) { acc += raw[ci * MAX_BUF + bi]; raw[ci * MAX_BUF + bi] = acc; }
    }
    return visited;
}

/* cycle members of the smallest-branch map, excluded as roots */
static int in_cycle(uint64_t v, int q) {
    if (q == 5) {
        static const uint64_t c5[] = {1,3,13,33,83,17,27,43};
        for (int i = 0; i < 8; i++) if (v == c5[i]) return 1;
        return 0;
    }
    if (q == 3) return (v == 1);
    if (q == 7) return (v == 1 || v == 5 || v == 3);  /* conservative */
    return v == 1;
}

int main(int argc, char **argv) {
    int q = 5, n_roots = 300, mode = MODE_ARITH, cp_lo = 4, cp_hi = 8, buf_lo = 9, buf_hi = 13;
    uint64_t fixedroot = 0;
    uint64_t root_lo = 101, root_hi = 9999, seed = 2026;
    const char *out = NULL;
    const char *rootlist = NULL;

    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--q"))        q = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--roots")) n_roots = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--iid"))   mode = MODE_IID;
        else if (!strcmp(argv[i], "--cyc"))   mode = MODE_CYC;
        else if (!strcmp(argv[i], "--cycq")) { mode = MODE_CYCQ; QVAL_LOG10 = log10(atof(argv[++i])); }
        else if (!strcmp(argv[i], "--iidq")) { mode = MODE_IIDQ; QMODE_IID = 1; QVAL_LOG10 = log10(atof(argv[++i])); }
        else if (!strcmp(argv[i], "--minlog")) MIN_LOG10 = atof(argv[++i]);
        else if (!strcmp(argv[i], "--fixedroot")) fixedroot = strtoull(argv[++i],0,10);
        else if (!strcmp(argv[i], "--cp"))  { cp_lo = atoi(argv[++i]); cp_hi = atoi(argv[++i]); }
        else if (!strcmp(argv[i], "--buf")) { buf_lo = atoi(argv[++i]); buf_hi = atoi(argv[++i]); }
        else if (!strcmp(argv[i], "--rootrange")) { root_lo = strtoull(argv[++i],0,10); root_hi = strtoull(argv[++i],0,10); }
        else if (!strcmp(argv[i], "--seed")) seed = strtoull(argv[++i],0,10);
        else if (!strcmp(argv[i], "--out"))  out = argv[++i];
        else if (!strcmp(argv[i], "--rootlist")) rootlist = argv[++i];
        else { fprintf(stderr, "unknown arg %s\n", argv[i]); return 1; }
    }
    setup_q(q);

    n_cp = cp_hi - cp_lo + 1; n_buf = buf_hi - buf_lo + 1;
    if (n_cp > MAX_CP || n_buf > MAX_BUF) { fprintf(stderr, "too many bins\n"); return 1; }
    for (int i = 0; i < n_cp; i++) { uint64_t v = 1; for (int e = 0; e < cp_lo + i; e++) v *= 10; cp[i] = v; }
    for (int i = 0; i < n_buf; i++) { uint64_t v = 1; for (int e = 0; e < buf_lo + i; e++) v *= 10; bufthr[i] = v; }
    BOUND = bufthr[n_buf - 1];
    for (int i = 0; i < n_cp; i++)  CP_LOG10[i]  = (double)(cp_lo + i);
    for (int i = 0; i < n_buf; i++) BUF_LOG10[i] = (double)(buf_lo + i);
    if ((mode == MODE_CYCQ || mode == MODE_IIDQ) && QVAL_LOG10 == 0.0) {
        fprintf(stderr, "--cycq / --iidq need a value\n"); return 1; }

    /* sample roots: odd, not divisible by q, not a cycle member, distinct */
    uint64_t *roots = NULL;
    if (rootlist) {
        int cnt = 1;
        for (const char *p = rootlist; *p; p++) if (*p == ',') cnt++;
        roots = (uint64_t *)malloc(cnt * sizeof(uint64_t));
        char *tmp = strdup(rootlist), *tok = strtok(tmp, ",");
        n_roots = 0;
        while (tok) { roots[n_roots++] = strtoull(tok, 0, 10); tok = strtok(NULL, ","); }
        free(tmp);
    } else {
    roots = (uint64_t *)malloc(n_roots * sizeof(uint64_t));
    if (fixedroot) {
        for (int i = 0; i < n_roots; i++) roots[i] = fixedroot;
    } else {
        uint64_t s = seed;
        int have = 0;
        while (have < n_roots) {
            uint64_t v = root_lo + (sm64(&s) % (root_hi - root_lo + 1));
            if (!(v & 1)) continue;
            if (v % (uint64_t)q == 0) continue;
            if (in_cycle(v, q)) continue;
            int dup = 0; for (int i = 0; i < have; i++) if (roots[i] == v) { dup = 1; break; }
            if (dup) continue;
            roots[have++] = v;
        }
    }
    }

    uint64_t *all = (uint64_t *)calloc((size_t)n_roots * MAX_CP * MAX_BUF, sizeof(uint64_t));
    uint64_t *allres = (uint64_t *)calloc((size_t)n_roots * 64, sizeof(uint64_t));
    uint64_t *nvis = (uint64_t *)calloc(n_roots, sizeof(uint64_t));

    fprintf(stderr, "q=%d d=%d mode=%s roots=%d cp=1e%d..1e%d buf=1e%d..1e%d\n",
            q, Dd, MODENAME[mode], n_roots, cp_lo, cp_hi, buf_lo, buf_hi);

#pragma omp parallel for schedule(dynamic, 1)
    for (int i = 0; i < n_roots; i++) {
        uint64_t sd = seed * 1000003ULL + (uint64_t)i * 7919ULL + 1;
        nvis[i] = (mode == MODE_CYCQ || mode == MODE_IIDQ)
            ? dfs_root_q(roots[i], sd, all + (size_t)i * MAX_CP * MAX_BUF)
            : dfs_root(roots[i], mode, sd, all + (size_t)i * MAX_CP * MAX_BUF,
                       allres + (size_t)i * 64);
    }

    FILE *f = out ? fopen(out, "w") : stdout;
    fprintf(f, "# q=%d mode=%s roots=%d cp_lo=%d cp_hi=%d buf_lo=%d buf_hi=%d seed=%llu\n",
            q, MODENAME[mode], n_roots, cp_lo, cp_hi, buf_lo, buf_hi,
            (unsigned long long)seed);
    fprintf(f, "# root nvisited then n_cp*n_buf cumulative counts N(val<=cp[ci], pmax<=buf[bi]) row-major ci,bi\n");
    for (int i = 0; i < n_roots; i++) {
        fprintf(f, "%llu %llu", (unsigned long long)roots[i], (unsigned long long)nvis[i]);
        for (int ci = 0; ci < n_cp; ci++)
            for (int bi = 0; bi < n_buf; bi++)
                fprintf(f, " %llu", (unsigned long long)all[(size_t)i * MAX_CP * MAX_BUF + ci * MAX_BUF + bi]);
        fprintf(f, "\n");
    }
    /* pooled residue histogram of counted nodes */
    fprintf(f, "#resid");
    for (int r = 0; r < q; r++) {
        unsigned long long s = 0;
        for (int i = 0; i < n_roots; i++) s += allres[(size_t)i * 64 + r];
        fprintf(f, " %llu", s);
    }
    fprintf(f, "\n");
    if (out) fclose(f);
    fprintf(stderr, "cemetery: %llu node(s) reached value 0\n", (unsigned long long)zero_nodes);
    return 0;
}
